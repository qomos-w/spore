func TestRender_OptionalScalarOmitemptyTag(t *testing.T) {
	objs := []schema.ObjectDesc{
		{
			Kind: schema.TypeKindStruct,
			Name: "Person",
			Fields: []schema.FieldDesc{
				{Name: "name", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}},
				{Name: "nickname", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}, Optional: true},
				{Name: "age", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "int"}, Optional: true},
			},
		},
	}
	out, err := Render(objs, Options{Package: "p"})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	got := normalizeWhitespace(string(out))
	if !strings.Contains(got, "Name string `json:\"name\"`") {
		t.Errorf("expected required name without omitempty, got:\n%s", got)
	}
	if !strings.Contains(got, "Nickname string `json:\"nickname,omitempty\"`") {
		t.Errorf("expected optional nickname with omitempty, got:\n%s", got)
	}
	if !strings.Contains(got, "Age int32 `json:\"age,omitempty\"`") {
		t.Errorf("expected optional age with omitempty, got:\n%s", got)
	}
}

func TestRender_OptionalStructFieldEmitsPointer(t *testing.T) {
	// Optional + named struct → pointer-to-struct so callers can distinguish
	// absent from zero-valued embedded objects (the existing TurnEvent-style
	// nullable variant pattern in myxos).
	objs := []schema.ObjectDesc{
		{
			Kind: schema.TypeKindStruct,
			Name: "TurnEvent",
			Fields: []schema.FieldDesc{
				{Name: "kind", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}},
				{Name: "started", Type: schema.TypeDesc{Kind: schema.TypeKindStruct, Name: "StartedPayload"}, Optional: true},
			},
		},
		{
			Kind: schema.TypeKindStruct,
			Name: "StartedPayload",
			Fields: []schema.FieldDesc{
				{Name: "turnId", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}},
			},
		},
	}
	out, err := Render(objs, Options{Package: "p"})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	got := normalizeWhitespace(string(out))
	if !strings.Contains(got, "Started *StartedPayload `json:\"started,omitempty\"`") {
		t.Errorf("expected pointer + omitempty for optional struct field, got:\n%s", got)
	}
	// Non-optional struct field should stay non-pointer (sanity check).
	objs2 := []schema.ObjectDesc{
		{
			Kind: schema.TypeKindStruct,
			Name: "Wrap",
			Fields: []schema.FieldDesc{
				{Name: "inner", Type: schema.TypeDesc{Kind: schema.TypeKindStruct, Name: "Inner"}},
			},
		},
	}
	out2, err := Render(objs2, Options{Package: "p"})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.Contains(string(out2), "Inner Inner `json:\"inner\"`") {
		t.Errorf("expected non-pointer required struct field, got:\n%s", out2)
	}
}

