func TestExportName_Initialisms(t *testing.T) {
	cases := []struct {
		in, want string
	}{
		// already-PascalCase identity cases
		{"AgentType", "AgentType"},
		{"Workspace", "Workspace"},

		// single initialisms
		{"id", "ID"},
		{"url", "URL"},
		{"json", "JSON"},

		// trailing initialism, lowerCamel input
		{"projectID", "ProjectID"},
		{"projectId", "ProjectID"},
		{"sessionID", "SessionID"},
		{"actorID", "ActorID"},
		{"actorId", "ActorID"},
		{"layoutJSON", "LayoutJSON"},
		{"workspaceID", "WorkspaceID"},

		// leading initialism
		{"aiShell", "AIShell"},
		{"htmlPage", "HTMLPage"},
		{"jsonData", "JSONData"},

		// PascalCase input with initialism word boundaries
		{"WorkspaceID", "WorkspaceID"},
		{"LayoutJSON", "LayoutJSON"},
		{"AIShell", "AIShell"},
		{"HTMLPage", "HTMLPage"},

		// non-initialism multi-word
		{"agentKind", "AgentKind"},
		{"mountName", "MountName"},

		// snake_case input
		{"old_string", "OldString"},
		{"new_string", "NewString"},
		{"replace_all", "ReplaceAll"},
		{"output_mode", "OutputMode"},
		{"file_id", "FileID"},
		{"api_url", "APIURL"},

		// empty + single letter edge cases
		{"", ""},
		{"x", "X"},
		{"X", "X"},
	}
	for _, tc := range cases {
		got := exportName(tc.in)
		if got != tc.want {
			t.Errorf("exportName(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}
