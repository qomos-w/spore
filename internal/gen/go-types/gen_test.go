func TestRender_SingleStruct(t *testing.T) {
	objs := []schema.ObjectDesc{
		{
			Kind: schema.TypeKindStruct,
			Name: "AgentChatSubmitReq",
			Fields: []schema.FieldDesc{
				{Name: "text", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}},
				{Name: "model", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}},
				{Name: "intent", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}},
				{Name: "agentType", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}},
			},
		},
	}

	out, err := Render(objs, Options{
		Package:    "agentchat",
		Header:     "// Code generated by spore-gen-go-types. DO NOT EDIT.",
		SourcePath: "schemas/agent.chat.spore",
	})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}

	want := `// Code generated by spore-gen-go-types. DO NOT EDIT.
// Source: schemas/agent.chat.spore

package agentchat

type AgentChatSubmitReq struct {
	Text      string ` + "`json:\"text\"`" + `
	Model     string ` + "`json:\"model\"`" + `
	Intent    string ` + "`json:\"intent\"`" + `
	AgentType string ` + "`json:\"agentType\"`" + `
}
`
	if string(out) != want {
		t.Fatalf("Render mismatch:\n--- got ---\n%s\n--- want ---\n%s", out, want)
	}
}

func TestRender_SortsStructsByName(t *testing.T) {
	objs := []schema.ObjectDesc{
		{
			Kind: schema.TypeKindStruct,
			Name: "Zebra",
			Fields: []schema.FieldDesc{
				{Name: "stripes", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "int"}},
			},
		},
		{
			Kind: schema.TypeKindStruct,
			Name: "Alpha",
			Fields: []schema.FieldDesc{
				{Name: "letter", Type: schema.TypeDesc{Kind: schema.TypeKindScalar, Name: "string"}},
			},
		},
	}

	out, err := Render(objs, Options{Package: "p"})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	got := string(out)
	alphaIdx := strings.Index(got, "type Alpha")
	zebraIdx := strings.Index(got, "type Zebra")
	if alphaIdx < 0 || zebraIdx < 0 {
		t.Fatalf("expected both types in output, got:\n%s", got)
	}
	if alphaIdx > zebraIdx {
		t.Fatalf("expected Alpha before Zebra in output, got:\n%s", got)
	}
}

